def deduplicate_by_title(articles: list[dict], prefer: Optional[dict] = None) -> list[dict]:
    """
    제목이 완전히 동일한 기사는 처음 나온 1건만 남긴다.
    (제목이 다르면, 같은 사건을 다룬 기사여도 그대로 모두 남긴다 — PRD.md 기능1 규칙 4)

    주의: "먼저 나온 것"이 남으므로, 언론사 우선순위 정렬(PLAN #5) 이후에
    호출해야 동일 제목 중 우선순위 높은 언론사의 기사가 남는다. archive/DESIGN.md
    데이터 흐름도 참고.

    prefer: [추가: 2026-09-11] {url: 처음 초안에 보인 순번} — 같은 제목 묶음 안에 여기
    적힌 기사가 있으면 **정렬 순서와 무관하게 그 기사가 대표로 남는다**(여럿이면 가장
    먼저 보인 것). 초안에 이미 보인 기사가 나중에 들어온 같은 제목 기사에 대표 자리를
    뺏겨 담당자 눈앞에서 사라지지 않게 하는 장치다(app.draft_seen 규칙 ①). 남는 자리는
    그 대표 기사 자신의 정렬 위치다. 초안과 확정본이 **같은 값**을 넘겨야 두 화면의
    대표가 같아진다(2026-09-02 쌍둥이 사고와 같은 이유).
    """
    chosen: dict = {}
    if prefer:
        for article in articles:
            seen_at = prefer.get(article.get("url"))
            if seen_at is None:
                continue
            title = article["title"]
            if title not in chosen or seen_at < prefer[chosen[title]]:
                chosen[title] = article["url"]
    seen_titles = set()
    unique_articles = []
    for article in articles:
        title = article["title"]
        if title in seen_titles:
            continue
        if title in chosen and article.get("url") != chosen[title]:
            continue
        seen_titles.add(title)
        unique_articles.append(article)
    return unique_articles
