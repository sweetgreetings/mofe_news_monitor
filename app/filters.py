# 제목 문자열에 **부분일치**로 대조했는데, 그건 [단독]·[속보](HEADLINE_TAG_RE)와 일정
# 나열 기사(_SCHEDULE_LISTING_RE)가 이미 "괄호 말머리만 인정, 부분일치 배제"로 피해간
