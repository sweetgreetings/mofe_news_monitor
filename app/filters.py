# 위치는 맨 앞으로 안 묶는다 — 실측 49건 중 1건(이투데이 "한성숙 총리, … 기자회견 [포토]")
# 이 제목 **끝**에 붙어 있었다. 잃은 진양성 1건: 뉴시스 "사진으로 보는 지난 주말
# [뉴시스Pic]" — 진짜 사진 모음 기사지만 [포토] 계열 표식이 없다. 매체 고유 표식
# ([뉴시스Pic] 등)까지 넣는 건 진양성 표본이 이 1건뿐이라 보류한다(아래
# _PHOTO_CAPTION_SUMMARY_PATTERNS "촬영 날짜 도장" 항목과 같은 이유).
# [수정: 2026-09-15] 매체 고유 표식 중 `[헤럴드pic]`만 따로 넣었다 — 아래 _OUTLET_PHOTO_TAG_RE.
PHOTO_TAG_RE = re.compile(
    r"[\[\(<〈《【〔]\s*[^\]\)>〉》】〕]{0,6}포토[^\]\)>〉》】〕]{0,8}[\]\)>〉》】〕]"
)
# [추가: 2026-09-15] 매체 고유 사진 표식 — "포토"라는 글자가 없는 말머리. 사용자 제보 —
# 헤럴드경제 `[헤럴드pic] 당당·초조·여유…누가 통과할까`가 배지 없이 떴다(제목이 질문형에
# `…`까지 있고 요약도 도장 앞에서 잘려, 표식 말고는 단서가 없는 기사다). 실측(저장 회차·
# trash·수시 카드·캐시 고유 기사 8,665건 전수): `[헤럴드pic]` 14건이 **전부 캡션**
# (`…참석하고 있다.`·`윤창빈 기자`), 기존 판정 적중 0건, 8/13~9/15에 흩어진 독립 사례들.
# **`pic`/`픽` 일반으로 넓히지 않는다** — 서울경제 `[Pick코노미]`(정책 기사 15건)·`[AI픽]`·
# `[논설실 Pick]`·`[이코노픽]`이 전부 일반 기사다. `[뉴시스Pic]`·`[뉴스1PICK]`은 사진 중심
# 기사와 발언 기사가 섞여 있어(`장동혁 … "재판 취소용 개각" [뉴시스Pic]`) 여전히 보류한다.
# 새 매체 표식은 **실측으로 전부 캡션인 걸 확인한 것만** 여기 더한다.
_OUTLET_PHOTO_TAG_RE = re.compile(
    r"[\[\(<〈《【〔]\s*헤럴드\s*pic\s*[\]\)>〉》】〕]", re.IGNORECASE
)
