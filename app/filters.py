# [추가: 2026-08-20] 제목 맨 앞 [단독]/[속보] 말머리 판정 — app.live_renderer(실시간 현황
# 글자색), app.renderer/app.preview_renderer(확정본·초안 글자색+카드 강조+[단독] 소제목
# 내 최상단 정렬)가 공유한다. 부분일치는 배제하고 맨 앞만 인정한다(괄호 변형
# []()<>《》【】〔〕 허용) — 저장된 고유 제목 1,339건 전수조사에서 괄호형 말머리는 전부
# 맨 앞에만 나왔고, 부분일치로 걸렀다면 "…단독명의" 같은 오탐이 1건 걸렸을 것(실측,
# HISTORY.md "[단독]·[속보] 필터" 참고).
HEADLINE_TAG_RE = re.compile(r"^[\[\(<〈《【〔]\s*(단독|속보)\s*[\]\)>〉》】〕]")


def headline_kind(title: str) -> Optional[str]:
    """제목 맨 앞의 [단독]/[속보] 말머리를 판정한다. 아니면 None."""
    match = HEADLINE_TAG_RE.match(title)
    return match.group(1) if match else None


# [추가: 2026-09-16] 사설 말머리 판정 — 실시간 현황 특수조건 줄의 `[사설]` 체크박스
# **하나만** 쓴다. HEADLINE_TAG_RE에 "사설"을 끼워 넣지 않고 정규식을 따로 둔 이유:
# 그 상수는 텔레그램 [단독]·[속보] 알림(app.breaking_alert_sender)·제목 글자색·
# [단독] 소제목 내 최상단 정렬(sort_scoop_first)·사진 추정 예외까지 함께 물고 있어서,
# 거기에 한 글자를 더하면 담당자가 요청한 적 없는 사설 알림이 밖으로 나간다.
#
# **맨 앞만 인정하는 [단독]·[속보]와 달리 위치를 안 가린다**(has_photo_tag와 같은 .search).
# 저장된 고유 제목 6,874건 전수 실측(2026-09-16): 괄호형 `[사설]` 50건 중 7건이
# **제목 끝**에 붙어 있었다(한국경제·조선일보 등 — `…규제 비현실적이라는 뜻 [사설]`).
# 맨 앞만 봤다면 그 7건(14%)을 놓쳤을 것이고, 오탐은 0건이었다. 괄호 안이 정확히
# "사설"일 때만 인정하므로 `[전국 주요 신문 사설](14일 조간)`(사설을 모아 소개하는
# 일반 기사) 2건은 걸리지 않는다 — 그게 맞는 판정이다.
EDITORIAL_TAG_RE = re.compile(r"[\[\(<〈《【〔]\s*사설\s*[\]\)>〉》】〕]")


def is_editorial(title: str) -> bool:
    """제목에 `[사설]` 괄호 말머리가 붙어 있는지 판정한다(위치 무관)."""
    return bool(EDITORIAL_TAG_RE.search(title or ""))


def has_photo_tag(title: str) -> bool:
    """제목에 [포토] 계열 괄호 말머리(또는 `[헤럴드pic]` 같은 매체 고유 사진 표식)가
    붙어 있는지 판정한다(위치 무관).

    이건 **추정이 아니라 언론사가 자기 손으로 붙인 표식**이라, 요약 모양·제목 모양을
    보고 알아맞히는 looks_like_photo_caption의 다른 신호들과 성격이 다르다 — 언론사가
    캡션 쓰는 법을 바꿔도 이 판정엔 새 구멍이 안 난다.
    """
    return photo_tag_text(title) is not None


def photo_tag_text(title: str) -> Optional[str]:
    """제목에 붙은 사진 표식 말머리 글자 그대로(예: `[포토]`, `[헤럴드pic]`). 없으면 None."""
    match = PHOTO_TAG_RE.search(title) or _OUTLET_PHOTO_TAG_RE.search(title)
    return match.group(0).strip() if match else None


def _body_verdict(url: str) -> Optional[bool]:
    """원문 판정 결과(없으면 None). app.photo_body는 naver_api 쪽을 거쳐 이 모듈을 부르지
    않지만, 순수 도구인 이 모듈이 import 시점에 네트워크 모듈을 끌어오지 않도록 늦게 읽는다."""
    from app import photo_body
    return photo_body.verdict(url)


def photo_badge_tip(title: str, url: str = "") -> str:
    """📷 사진 추정 배지의 툴팁 문구 — 확정본·초안·실시간 현황·수시가 함께 쓴다.

    [추가: 2026-09-15] 배지 글자는 표식·추정 모두 「📷 사진 추정」 하나이고 정확성은 여기서만
    갈린다(CLAUDE.md 사진기사 항목). 표식이면 **실제로 붙은 말머리**를 그대로 적는다 —
    `[헤럴드pic]` 기사에 "[포토] 표식이 붙은"이라 쓰면 틀린 말이다. 예전엔 같은 문구가
    화면 셋에 따로 적혀 있었고, 수시는 표식 기사에도 늘 "표식은 없지만"이라고 했다.
    반환값은 제목에서 온 글자를 담으므로 속성에 넣을 땐 이스케이프한다.
    """
    tag = photo_tag_text(title)
    if tag:
        return f"제목에 {tag} 표식이 붙은 사진기사입니다"
    if url and _body_verdict(url):
        return "원문이 사진과 설명 한 문장뿐인 사진기사입니다"
    return "제목에 [포토] 표식은 없지만 사진기사로 추정됩니다"


