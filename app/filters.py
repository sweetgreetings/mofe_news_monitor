# 확대 2.8조 투입`, `공공기관 109개 줄인다…LH는 분리` 같은 핵심 정책 기사들). 그래서
# 임계값은 그 빈 구간에 둔다. 적용 결과 563건 → 551건, **잃은 진양성 0건**.
_CAPTION_TAIL_MAX_HANGUL = 10
_HANGUL_RE = re.compile(r"[가-힣]")


def _summary_signal_at_tail(summary: str) -> bool:
    """캡션 신호 중 하나라도 요약의 끝자락을 차지하고 있으면 True.

    신호마다 **마지막** 등장 위치를 기준으로 본다 — 캡션이 여러 번 나오는 요약에서
    앞쪽 등장만 보면 뒤에 붙은 진짜 캡션을 놓친다.
    """
    for pattern in _PHOTO_CAPTION_SUMMARY_PATTERNS:
        matches = list(pattern.finditer(summary))
        if not matches:
            continue
        tail = summary[matches[-1].end():]
        if len(_HANGUL_RE.findall(tail)) < _CAPTION_TAIL_MAX_HANGUL:
            return True
    return False


