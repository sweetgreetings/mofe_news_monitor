# 4,903건 전수, 2026-09-03): 부분일치 54건 - 말머리 49건 = 차이 5건이 **전부 오탐**이었다.
#   - `이언주 "…세제 강화보다 정책 무게 둬야"`      ← 강[화보]다. 딱 "…단독명의" 유형
#   - `"냉면이 징그러워"…AI로 만든 메뉴 사진에…`     ← 진짜 기사
#   - `"냉면·국수 사진, 보기만 해도 속이 울렁"…`     ← 진짜 기사
