# 홈의 쟁점 순위 계산에서만 걸러 쓴다(HISTORY.md "홈 화면 재구성" 참고).
_SCHEDULE_LISTING_RE = re.compile(r"^\s*[\[\(<《【〔][^\]\)>》】〕]{0,20}일정[^\]\)>》】〕]{0,10}[\]\)>》】〕]")


def is_schedule_listing(title: str) -> bool:
    """제목 맨 앞 말머리 안에 "일정"이 있는 정형 일정 나열 기사인지 판정한다."""
    return bool(_SCHEDULE_LISTING_RE.match(title))


def sort_scoop_first(articles: list[dict]) -> list[dict]:
    """[단독] 기사를 안정 정렬로 앞쪽에 둔다(그 외 상대 순서는 그대로 유지).

    [추가: 2026-08-20] app.classifier.classify_articles가 "그룹 내 기사 순서는 입력
    순서를 유지"하므로(CLAUDE.md), 소제목으로 나뉘기 전인 이 시점에 전체 목록에서
    [단독]만 안정 정렬로 앞으로 보내두면, 나중에 소제목별로 갈라져도 "그 소제목 안에서
    [단독]이 맨 위"가 저절로 성립한다(각 소제목은 이 목록의 부분수열이라 상대 순서가
    그대로 보존됨). 언론사 우선순위 정렬 이후, app.preview_order.apply_preview_order
    (담당자가 직접 옮긴 순서)보다는 반드시 앞에서 호출해야 한다 — 담당자의 ↑/↓가
    이 자동 정렬을 항상 이겨야 하기 때문(CLAUDE.md 큐레이션 규칙).

    [속보]는 서열상 [단독] 다음이라 자리를 옮기지 않는다 — 색으로만 눈에 띄게 하고
    정렬은 건드리지 않는다(속보는 한 회차에 여러 건 나올 수 있어, 전부 끌어올리면
    정작 가장 중요한 [단독]이 그 사이에 묻힌다).
    """
    return sorted(articles, key=lambda a: headline_kind(a["title"]) != "단독")


def filter_by_outlet_whitelist(articles: list[dict], whitelist: list[str]) -> list[dict]:
    """설정 화면에서 고른 언론사(whitelist)에 없는 기사는 제외한다 (PRD.md 기능1 규칙 16).

    whitelist가 비어 있으면 아무것도 걸러내지 않는다 — "언론사를 하나도 안 골랐다"는
    PRD상 "화이트리스트 미사용, 기본 우선순위 유지"를 뜻하므로, 호출 여부 자체를
    호출하는 쪽(app.scraper)이 whitelist 존재 여부로 판단한다.
    """
    if not whitelist:
        return articles
    allowed = set(whitelist)
    return [a for a in articles if a["outlet"] in allowed]


