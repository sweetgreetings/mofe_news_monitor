# exclude_photo_in_scrap이 기본 꺼짐이라 아무도 못 봤을 뿐, 그 설정을 켜면 위 기사들이
# 화면 어디에도 흔적 없이 사라졌다("과잉 숨김은 안 보인다" — CLAUDE.md Curation 참고).
