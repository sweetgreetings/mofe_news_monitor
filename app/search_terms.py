# Design Ref: CLAUDE.md "검색어 연산자" — 띄어쓰기는 한 덩어리, `+`가 AND. 다섯 자리가 한 규칙.
"""검색어 한 칸을 읽는 규칙 한 곳.

담당자가 검색어 칸에 적는 말의 뜻은 앱 어디서나 같다:

- **띄어쓰기는 한 덩어리다** — `가상자산 과세`는 그 말이 붙어 있는 기사.
- **`+`가 AND다** — `가상자산 과세+이형일`은 「가상자산 과세」가 붙어 있고 「이형일」도 든 기사.

칸 하나 안에 OR는 없다. OR는 검색어를 따로 두는 것 그 자체다(정기는 그룹 안 낱개 키워드,
수시는 검색어 칸의 낱개 검색어).

이 규칙을 쓰는 자리는 둘로 갈리고, 둘 다 여기를 거친다:

- **네이버에 물어보는 칸**(정기 검색어 · 수시 새 수집) → `naver_query`로 옮겨 넘긴다.
- **쌓인 글자와 대조하는 칸**(기관 기사 찾기 · 정책 단어 추이 · 형광펜) → `split_terms`로
  조각을 내 전부 든 것만 고른다.

**새 검색어 칸을 만들면 반드시 이 둘 중 하나를 쓴다** — 자기 자리에서 직접 `split("+")`
하거나 문자열을 네이버에 그대로 넘기면 그 칸만 규칙이 달라지고, 담당자는 칸마다 뜻이
바뀌는 것을 알 길이 없다.
"""


def split_terms(word: str) -> list[str]:
    """검색어 한 칸을 `+`로 가른 조각들.

    **띄어쓰기는 가르지 않는다** — 띄어 쓴 말은 붙어 있는 그대로 찾는 한 덩어리다.
    """
    return [t for t in (part.strip() for part in (word or "").split("+")) if t]


def naver_query(word: str) -> str:
    """검색어 한 칸을 네이버 뉴스 검색 질의로 옮긴다.

    네이버의 규칙은 앱의 규칙과 다르다 — 질의의 공백을 낱말 경계로 보고 그 낱말이 전부 든
    기사를 주고(AND), 겹따옴표로 묶은 말만 붙어 있는 그대로 찾는다. 실측(2026-09-30,
    받은 100건 중 「가상자산 과세」가 붙어 있는 기사 수):

        가상자산 과세      total 27,200 →  67건   (= 가상자산+과세, 완전히 같다)
        "가상자산 과세"    total 11,015 →  98건

    그래서 **띄어 쓴 조각을 겹따옴표로 감싸** 네이버가 덩어리로 찾게 하고, 조각 사이는
    공백으로 이어 AND로 돌린다. `"가상자산 과세" 이형일`이 실제로 그렇게 동작하는 것도
    같은 날 실측했다(받은 100건 중 87건이 덩어리 + 「이형일」 둘 다 만족).

    담당자가 직접 겹따옴표를 적은 조각은 그대로 넘긴다 — 네이버 문법을 알고 쓴 것이라
    앱이 한 겹 더 감싸면(`""…""`) 질의가 깨진다.
    """
    terms = split_terms(word)
    if not terms:
        return (word or "").strip()
    out = []
    for term in terms:
        # 조각 안 여러 칸·줄바꿈은 한 칸으로 눕힌다(네이버에 넘기는 값이라 정규화한다).
        term = " ".join(term.split())
        if '"' in term:
            out.append(term)  # 담당자가 적은 겹따옴표 — 손대지 않는다
        elif " " in term:
            out.append(f'"{term}"')
        else:
            out.append(term)
    return " ".join(out)
