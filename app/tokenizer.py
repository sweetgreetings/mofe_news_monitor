# 단어 경계로 쓸 문자: 공백과 각종 문장부호·괄호.
_SPLIT_PATTERN = re.compile(r"[\s\[\]()<>·,…\"'“”‘’!?.·:;/\\|~\-—]+")

# [추가: 2026-07-24] "24일"·"3월"·"오후 2시"처럼 숫자+날짜/시간 단위로만 된 단어는 거의 항상
# 그날의 날짜·시각 표현이라 소제목감이 못 된다 (예: 요약문 대부분에 "24일"이 들어있어 그
# 자체로 소제목이 되어버리는 문제). 며칠이 지나도 계속 나올 패턴이라 불용어 목록에 하나씩
# 추가하는 대신 패턴으로 걸러낸다.
_DATE_TIME_PATTERN = re.compile(r"^\d+(일|월|년|시|분|초|주)$")


# [추가: 2026-07-31] "회의"는 조사 "의"가 명사 뒤에 붙은 형태가 아니라, "경제관계장관회의"
# ·"비상경제본부회의"처럼 그 자체가 하나의 고유명사(회의체 이름)의 일부다. 조사 "의"를
# 기계적으로 떼면 "...회의"가 "...회"로 잘못 잘린다(예: "경제관계장관회의" -> "경제관계장관회").
# 이런 회의체 이름은 소제목·워드클라우드에서 오히려 의미 있는 고유명사이므로, "의"를 뗄
# 때만 "회의"로 끝나는 경우를 예외로 두어 통째로 보존한다. 나중에 비슷한 사례(다른
# "-의" 복합명사)가 또 보이면 이 튜플에 하나씩 추가한다.
_PROTECTED_UI_ENDINGS = ("회의",)


def _strip_suffix(word: str, suffixes: tuple) -> str:
    for suffix in suffixes:
        if suffix == "의" and word.endswith(_PROTECTED_UI_ENDINGS):
            continue
        if len(word) > len(suffix) + 1 and word.endswith(suffix):
            return word[: -len(suffix)]
    return word


def tokenize(title: str, stopwords: set) -> set:
    """제목을 의미 단어 집합으로 바꾼다 (2글자 이상, 조사/어미 제거, 불용어·검색 키워드·날짜 제외)."""
    tokens = set()
    for raw in _SPLIT_PATTERN.split(title):
        word = raw.strip()
        if not word or word in _JOSA:
            continue  # [수정: 2026-07-25] "에서"처럼 조사 하나만 통째로 떨어져 나온 토큰은 버린다
        word = _strip_suffix(_strip_suffix(word, _JOSA), _EOMI).lower()
        if len(word) >= 2 and word not in stopwords and not _DATE_TIME_PATTERN.match(word):
            tokens.add(word)
    return tokens
